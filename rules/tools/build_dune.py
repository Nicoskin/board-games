def ic(name, cls='ic'):
    w, h = SIZES[f'icons/{name}.png']
    alt = ICON_ALT[name]
    return f'<img width="{w}" height="{h}" class="{cls}" src="img/dune/icons/{name}.png" alt="{alt}" title="{alt}">'


def img(path, alt, cls=''):
    w, h = SIZES[path]
    c = f' class="{cls}"' if cls else ''
    return f'<img width="{w}" height="{h}"{c} src="img/dune/{path}" alt="{alt}" loading="lazy">'


def fig(path, alt, cap='', cls=''):
    c = f' class="{cls}"' if cls else ''
    cp = f'<figcaption>{cap}</figcaption>' if cap else ''
    return f'<figure{c}>{img(path, alt)}{cp}</figure>'


