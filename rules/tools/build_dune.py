def src(book, n, label=None):
    f = f'img/dune/{book}-{n:02d}.jpg'
    return f'<a class="src" data-zoom="{f}" href="{f}">{BOOK[book][0]} {label or n}</a>'


def cell(cid, pic, name, meta, text, keys=''):
    k = f' data-keys="{keys}"' if keys else ''
    m = ''.join(f'<span>{x}</span>' for x in meta)
    return (f'<section id="cell-{cid}" class="cell" data-notoc{k}><h4>{name}</h4>'
            f'{img("cells/" + pic + ".jpg", "Ячейка «" + name + "»")}<p class="cell-meta">{m}</p><p>{text}</p></section>')


def sym(sid, icons, name, text):
    pics = ''.join(ic(i) for i in icons)
    return f'<section id="sym-{sid}" class="sym" data-notoc><h4>{pics} {name}</h4><p>{text}</p></section>'


